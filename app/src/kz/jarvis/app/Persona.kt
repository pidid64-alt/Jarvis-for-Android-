    /**
     * Системный промпт с точными часами телефона. Этим надо кормить модель,
     * а не голым [SYSTEM_PROMPT]: иначе она не знает, который час.
     */
    fun live(now: Long = System.currentTimeMillis()): String {
        val clock = SimpleDateFormat("HH:mm", Locale.getDefault()).format(Date(now))
        val date = SimpleDateFormat("EEEE, d MMMM yyyy", Locale("ru")).format(Date(now))
        return SYSTEM_PROMPT +
            " Сейчас на телефоне владельца $clock, $date. Это точные часы устройства — называй именно это время."
    }
